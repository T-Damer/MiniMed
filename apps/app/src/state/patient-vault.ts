/**
 * How the vault is stored, for the settings status. An Android vault still on the device key with
 * no secure lock screen to move to is told apart (`native-keychain-no-lock`): there nothing asks
 * for a fingerprint. A device-key vault on a phone that has a lock screen is only waiting for its
 * next unlock to move, so it reads as an ordinary protected one.
 */
export type PatientVaultDisplayState =
  | 'empty'
  | PatientVaultStorageMode
  | 'native-keychain-no-lock';

export async function patientVaultDisplayState(): Promise<PatientVaultDisplayState> {
  const stored = await readStoredVault();
  if (!stored) return 'empty';
  if (
    stored.mode === 'native-keychain' &&
    (stored.wrappedKey.protection ?? 'device') === 'device' &&
    !(await isNativePatientVaultAuthAvailable())
  ) {
    return 'native-keychain-no-lock';
  }
  return stored.mode;
}

export function lockPatientVault(): void {
  if (session?.mode === 'native-keychain') session.rawKey.fill(0);
  session = undefined;
  // A code that was never confirmed is not kept across a lock: the next unlock offers a fresh one.
  if (pendingRecovery) {
    pendingRecovery = undefined;
    emit(PATIENT_VAULT_RECOVERY_EVENT);
  }
  emit(PATIENT_VAULT_LOCK_EVENT);
}

/**
 * A new device-held data key for an encrypted vault: the Android Keystore wrapping a random key
 * when this is the app on a phone with a usable keychain, else a non-extractable browser key.
 * `build` puts the encrypted first snapshot into the stored record of the chosen mode.
 */
async function newEncryptedVault(): Promise<{
  readonly session: EncryptedSession;
  readonly build: (snapshot: EncryptedRecord) => NativeStoredVault | BrowserStoredVault;
  /** An auth-bound native vault: the code to show once the record is stored. */
  readonly recovery?: { readonly code: string; readonly blob: RecoveryBlob };
}> {
  if (isPatientVaultNativePlatform() && (await isNativePatientVaultKeychainAvailable())) {
    const dataKey = await generateDataKey();
    try {
      // With a secure lock screen the key is auth-bound: wrapping asks for a fingerprint / PIN.
      const protection: NativeKeyProtection = (await isNativePatientVaultAuthAvailable())
        ? 'auth'
        : 'device';
      // A stale auth key left by an earlier lock screen is replaced: there is no data to lose yet.
      const wrapped = await wrapPatientVaultKey(
        dataKey.rawKey,
        protection,
        protection === 'auth' ? { replaceInvalidatedKey: true } : undefined,
      );
      if (protection === 'auth') await assertWrappedKeyOpens(wrapped, protection, dataKey.rawKey);
      const wrappedKey: NativeWrappedKey = { ...wrapped, protection };
      // An auth-bound key can be deleted by Android, so it never stands alone.
      const recovery = protection === 'auth' ? await newRecovery(dataKey.rawKey) : undefined;
      return {
        session: { mode: 'native-keychain', ...dataKey },
        build: (snapshot) => ({
          schemaVersion: PATIENT_VAULT_SCHEMA_VERSION,
          mode: 'native-keychain',
          wrappedKey,
          ...(recovery ? { recovery: recovery.blob } : {}),
          snapshot,
        }),
        ...(recovery ? { recovery } : {}),
      };
    } catch (error) {
      dataKey.rawKey.fill(0);
      throw nativeKeyError(error, 'Keychain/Keystore не сохранил ключ хранилища.', 'storage');
    }
  }
  let key: CryptoKey;
  try {
    key = await generateBrowserDeviceKey();
  } catch (error) {
    throw error instanceof PatientVaultError
      ? error
      : new PatientVaultError(
          'Браузер не создал ключ шифрования. Можно продолжить без шифрования.',
          'unavailable',
        );
  }
  return {
    session: { mode: 'browser-device-key', key },
    build: (snapshot) => ({
      schemaVersion: PATIENT_VAULT_SCHEMA_VERSION,
      mode: 'browser-device-key',
      key,
      snapshot,
    }),
  };
}

/** A browser that cannot clone a CryptoKey into IndexedDB cannot keep the vault key. */
function asKeyStorageError(error: unknown, mode: EncryptedSession['mode']): PatientVaultError {
  if (error instanceof PatientVaultError && error.code !== 'storage') return error;
  return mode === 'native-keychain'
    ? asStorageError(error, 'Keychain/Keystore не сохранил ключ хранилища.')
    : new PatientVaultError(
        'Браузер не смог сохранить ключ шифрования. Можно продолжить без шифрования.',
        'unavailable',
      );
}

export async function createPatientVault(options?: {
  /** Fallback only for a browser that cannot keep the encryption key. */
  readonly allowUnencrypted?: boolean;
}): Promise<PatientVaultStorageMode> {
  if (await readStoredVault()) {
    throw new PatientVaultError('Пациентское хранилище уже создано.', 'storage');
  }
  if (options?.allowUnencrypted) {
    const stored: PlainStoredVault = {
      schemaVersion: PATIENT_VAULT_SCHEMA_VERSION,
      mode: 'unencrypted',
      snapshot: {
        type: 'patient-snapshot',
        id: 'current',
        version: PATIENT_VAULT_SCHEMA_VERSION,
        data: emptyPatientVaultSnapshot(),
      },
    };
    await writeStoredVault(stored);
    session = { mode: 'unencrypted' };
    emit(PATIENT_VAULT_EVENT);
    return stored.mode;
  }
  const setup = await newEncryptedVault();
  try {
    const encrypted = await encryptBytes(
      setup.session.key,
      utf8(JSON.stringify(emptyPatientVaultSnapshot())),
      'patient-snapshot',
      'current',
    );
    await writeStoredVault(
      setup.build({
        type: 'patient-snapshot',
        id: 'current',
        version: PATIENT_VAULT_SCHEMA_VERSION,
        ...encrypted,
      }),
      // Both blobs of an auth-bound vault reach the disk before the code is shown.
      setup.recovery ? { strictDurability: true } : undefined,
    );
  } catch (error) {
    if (setup.session.mode === 'native-keychain') setup.session.rawKey.fill(0);
    throw asKeyStorageError(error, setup.session.mode);
  }
  session = setup.session;
  emit(PATIENT_VAULT_EVENT);
  if (setup.recovery) offerRecoveryCode(setup.recovery.code, setup.recovery.blob);
  return setup.session.mode;
}

/**
 * Encrypts an existing unencrypted vault in place: the snapshot and every file are re-encrypted
 * under a new device key and written in ONE transaction, so a failure leaves the plain vault as it
 * was. Runs behind the mutation queue (file writers use it too), so nothing is written meanwhile.
 * The vault ends unlocked in the new mode.
 */
export async function encryptPatientVault(): Promise<PatientVaultStorageMode> {
  // An encrypted vault is only opened, outside the mutation queue: unlocking may write to it.
  const existing = await readStoredVault();
  if (existing && existing.mode !== 'unencrypted') {
    if (!session) await unlockPatientVault();
    return existing.mode;
  }
  return withPatientVaultMutation(async () => {
    const stored = await readStoredVault();
    if (!stored) throw new PatientVaultError('Пациентское хранилище ещё не создано.', 'storage');
    if (stored.mode !== 'unencrypted') return stored.mode;
    const snapshot = normalizePatientVaultSnapshot(stored.snapshot.data);
    const setup = await newEncryptedVault();
    try {
      const database = await openDatabase();
      try {
        const readTransaction = database.transaction(BLOB_STORE, 'readonly');
        const readDone = transactionDone(readTransaction);
        const blobs = await requestResult(
          readTransaction.objectStore(BLOB_STORE).getAll() as IDBRequest<StoredBlob[]>,
        );
        await readDone;
        const encryptedBlobs: EncryptedBlob[] = [];
        for (const blob of blobs) {
          assertStoredBlob(blob);
          if (blob.storage !== 'plaintext') {
            throw new PatientVaultError(
              'В нешифрованном хранилище найден зашифрованный файл.',
              'integrity',
            );
          }
          const { bytes, storage: _plain, ...base } = blob;
          encryptedBlobs.push({
            ...base,
            storage: 'encrypted',
            ...(await encryptBytes(setup.session.key, bytes, 'patient-file', blob.id)),
          });
        }
        const encryptedSnapshot = await encryptBytes(
          setup.session.key,
          utf8(JSON.stringify(snapshot)),
          'patient-snapshot',
          'current',
        );
        const transaction = database.transaction(
          [VAULT_STORE, BLOB_STORE],
          'readwrite',
          setup.recovery ? { durability: 'strict' } : undefined,
        );
        transaction.objectStore(VAULT_STORE).put(
          setup.build({
            type: 'patient-snapshot',
            id: 'current',
            version: PATIENT_VAULT_SCHEMA_VERSION,
            ...encryptedSnapshot,
          }),
          VAULT_KEY,
        );
        const blobStore = transaction.objectStore(BLOB_STORE);
        for (const blob of encryptedBlobs) blobStore.put(blob);
        await transactionDone(transaction);
      } finally {
        database.close();
      }
    } catch (error) {
      if (setup.session.mode === 'native-keychain') setup.session.rawKey.fill(0);
      throw asKeyStorageError(error, setup.session.mode);
    }
    session = setup.session;
    emit(PATIENT_VAULT_EVENT);
    if (setup.recovery) offerRecoveryCode(setup.recovery.code, setup.recovery.blob);
    return setup.session.mode;
  });
}

// --- Recovery code ----------------------------------------------------------------------------

/**
 * The recovery code is the diary doctor account's: `newRecoveryCode` (24 characters in groups of
 * four) and `deriveRecoverySecrets` (HKDF-SHA256, tolerant to case, spaces and dashes). The
 * derivation takes the account e-mail as its second input; the vault has none, so a fixed context
 * string stands in and keeps vault keys apart from account keys. Loaded on demand because that
 * module needs Web Crypto the moment it is imported.
 */
const RECOVERY_CONTEXT = 'minimed-patient-vault';
const RECOVERY_AAD = 'patient-vault-recovery:v1';
const WRONG_RECOVERY_CODE_MESSAGE = 'Код не подошёл';

let recoveryScheme: Promise<typeof import('@localmed/diary-sync')> | undefined;

function loadRecoveryScheme(): Promise<typeof import('@localmed/diary-sync')> {
  recoveryScheme ??= import('@localmed/diary-sync');
  return recoveryScheme;
}

async function sealDataKeyWithCode(
  rawKey: Uint8Array,
  code: string,
): Promise<NativeWrappedKeyShape> {
  const { deriveRecoverySecrets } = await loadRecoveryScheme();
  const { wrapKey } = await deriveRecoverySecrets(code, RECOVERY_CONTEXT);
  const iv = randomBytes(IV_BYTES);
  const ciphertext = await requireCrypto().subtle.encrypt(
    {
      name: 'AES-GCM',
      iv: arrayBuffer(iv),
      additionalData: arrayBuffer(utf8(RECOVERY_AAD)),
      tagLength: 128,
    },
    wrapKey,
    arrayBuffer(rawKey),
  );
  return { ivBase64: bytesToBase64(iv), ciphertextBase64: bytesToBase64(ciphertext) };
}

/** The data key a recovery blob holds, or `wrong-code` when this code does not open it. */
async function openDataKeyWithCode(blob: NativeWrappedKeyShape, code: string): Promise<Uint8Array> {
  try {
    const { deriveRecoverySecrets } = await loadRecoveryScheme();
    const { wrapKey } = await deriveRecoverySecrets(code, RECOVERY_CONTEXT);
    const plain = new Uint8Array(
      await requireCrypto().subtle.decrypt(
        {
          name: 'AES-GCM',
          iv: arrayBuffer(base64ToBytes(blob.ivBase64)),
          additionalData: arrayBuffer(utf8(RECOVERY_AAD)),
          tagLength: 128,
        },
        wrapKey,
        arrayBuffer(base64ToBytes(blob.ciphertextBase64)),
      ),
    );
    if (plain.byteLength !== AES_KEY_BYTES) throw new Error('unexpected key length');
    return plain;
  } catch {
    throw new PatientVaultError(WRONG_RECOVERY_CODE_MESSAGE, 'wrong-code');
  }
}

type NativeWrappedKeyShape = Pick<NativeWrappedKey, 'ivBase64' | 'ciphertextBase64'>;

async function assertRecoveryOpens(
  blob: NativeWrappedKeyShape | undefined,
  code: string,
  expected: Uint8Array,
): Promise<void> {
  if (!blob) throw new PatientVaultError('Код восстановления не сохранился.', 'storage');
  const opened = await openDataKeyWithCode(blob, code);
  try {
    if (!sameBytes(opened, expected)) {
      throw new PatientVaultError('Код восстановления открыл другой ключ хранилища.', 'integrity');
    }
  } finally {
    opened.fill(0);
  }
}

/** A fresh code and the blob it opens; the blob is proven to open exactly this key before use. */
async function newRecovery(
  rawKey: Uint8Array,
): Promise<{ readonly code: string; readonly blob: RecoveryBlob }> {
  const { newRecoveryCode } = await loadRecoveryScheme();
  const code = newRecoveryCode();
  const sealed = await sealDataKeyWithCode(rawKey, code);
  await assertRecoveryOpens(sealed, code, rawKey);
  return { code, blob: { ...sealed, confirmed: false } };
}

function sameRecoveryBlob(left: RecoveryBlob | undefined, right: RecoveryBlob): boolean {
  return (
    left !== undefined &&
    left.ivBase64 === right.ivBase64 &&
    left.ciphertextBase64 === right.ciphertextBase64 &&
    left.confirmed === right.confirmed
  );
}

function sameWrappedKey(left: NativeWrappedKey, right: NativeWrappedKey): boolean {
  return (
    left.ivBase64 === right.ivBase64 &&
    left.ciphertextBase64 === right.ciphertextBase64 &&
    (left.protection ?? 'device') === (right.protection ?? 'device')
  );
}

function offerRecoveryCode(code: string, blob: RecoveryBlob): void {
  pendingRecovery = { code, ivBase64: blob.ivBase64, ciphertextBase64: blob.ciphertextBase64 };
  emit(PATIENT_VAULT_RECOVERY_EVENT);
}

/** The code to show in «Код восстановления хранилища», until the doctor confirms it. */
export function pendingPatientVaultRecoveryCode(): string | undefined {
  return pendingRecovery?.code;
}

/**
 * «Я записал»: marks the stored blob confirmed and forgets the code. If the write fails the code
 * stays on screen and the error is thrown, so the doctor can try again.
 */
export function confirmPatientVaultRecoveryCode(): Promise<void> {
  return withPatientVaultMutation(async () => {
    const pending = pendingRecovery;
    if (!pending) return;
    const current = await readStoredVault();
    if (
      current?.mode === 'native-keychain' &&
      current.recovery &&
      current.recovery.ivBase64 === pending.ivBase64 &&
      current.recovery.ciphertextBase64 === pending.ciphertextBase64 &&
      !current.recovery.confirmed
    ) {
      await writeStoredVault(
        { ...current, recovery: { ...current.recovery, confirmed: true } },
        { strictDurability: true },
      );
    }
    if (pendingRecovery === pending) {
      pendingRecovery = undefined;
      emit(PATIENT_VAULT_RECOVERY_EVENT);
    }
  });
}

/** Whether this vault has a recovery code that can reopen it (Settings → «Восстановить по коду»). */
export async function patientVaultHasRecovery(): Promise<boolean> {
  const stored = await readStoredVault();
  return stored?.mode === 'native-keychain' && stored.recovery !== undefined;
}

const AUTH_PROMPT_MESSAGES = {
  AUTH_CANCELLED: 'Хранилище заблокировано. Подтвердите отпечаток или PIN, чтобы открыть.',
  AUTH_FAILED: 'Не удалось подтвердить. Попробуйте ещё раз.',
  AUTH_UNAVAILABLE: 'Не удалось запросить отпечаток или PIN. Проверьте блокировку экрана.',
} as const;

/**
 * The Keystore key was removed, which Android does when the lock screen is removed or replaced.
 * Nothing in the stored vault was touched. The way back in is the recovery code
 * (`recoverPatientVaultWithCode`) or a patients backup file saved earlier («Данные» → копия
 * пациентов) and restored from the patients list.
 */
export const PATIENT_VAULT_KEY_INVALIDATED_MESSAGE =
  'Ключ хранилища больше недействителен: на телефоне сменили или сняли блокировку экрана. ' +
  'Данные не удалены. Откройте их по коду восстановления или из ранее сохранённой копии пациентов.';

/**
 * A rejection of the native plugin as a vault error. A fingerprint / PIN prompt that did not
 * unlock the key is `auth-required` (retry later, nothing changed); a removed key is
 * `key-invalidated` (never reset or wiped automatically); anything else keeps `fallbackCode`.
 */
function nativeKeyError(
  error: unknown,
  fallback: string,
  fallbackCode: 'unavailable' | 'storage',
): PatientVaultError {
  if (error instanceof PatientVaultError) return error;
  const code = nativeVaultErrorCode(error);
  if (code === 'KEY_INVALIDATED') {
    return new PatientVaultError(PATIENT_VAULT_KEY_INVALIDATED_MESSAGE, 'key-invalidated');
  }
  if (code) return new PatientVaultError(AUTH_PROMPT_MESSAGES[code], 'auth-required');
  return new PatientVaultError(
    error instanceof Error && error.message ? error.message : fallback,
    fallbackCode,
  );
}

function sameBytes(left: Uint8Array, right: Uint8Array): boolean {
  return left.byteLength === right.byteLength && left.every((byte, index) => byte === right[index]);
}

/** The wrapped key opens to exactly `expected` (inside the check window, so no second prompt). */
async function assertWrappedKeyOpens(
  wrapped: NativeWrappedKey,
  protection: NativeKeyProtection,
  expected: Uint8Array,
): Promise<void> {
  const opened = await unwrapPatientVaultKey(wrapped, protection);
  try {
    if (!sameBytes(opened, expected)) {
      throw new PatientVaultError('Keystore вернул другой ключ хранилища.', 'integrity');
    }
  } finally {
    opened.fill(0);
  }
}

let upgradeInFlight: Promise<void> | undefined;

/**
 * Moves a vault from the device key to an auth-bound key, in an order that keeps the old way in
 * until the new one is proven:
 *
 * 1. wrap the (already verified) data key with the auth-bound key; this shows the system prompt;
 * 2. unwrap it again and compare, so a key that cannot be used is found before anything changes;
 *    seal the same data key under a fresh recovery code and check that it opens;
 * 3. replace only `wrappedKey` and `recovery` of the stored record, with strict IndexedDB
 *    durability and only if the record still holds the blob we unwrapped;
 * 4. read the record back from storage; unwrap the auth blob and open the recovery blob once more;
 * 5. only then offer the code to the doctor and ask the plugin to retire the device key.
 *
 * Nothing is deleted before step 5, so a failure anywhere leaves the old key and the old blob
 * working. A cancelled or failed prompt is thrown (`auth-required`: the vault stays locked,
 * nothing is lost); any other failure is logged and the vault opens as before and retries on the
 * next unlock. Concurrent unlocks share one upgrade.
 */
function upgradeToAuthProtection(legacy: NativeWrappedKey, rawKey: Uint8Array): Promise<void> {
  upgradeInFlight ??= runUpgradeToAuthProtection(legacy, rawKey).finally(() => {
    upgradeInFlight = undefined;
  });
  return upgradeInFlight;
}

async function runUpgradeToAuthProtection(
  legacy: NativeWrappedKey,
  rawKey: Uint8Array,
): Promise<void> {
  try {
    if (!(await isNativePatientVaultAuthAvailable())) return;
    // The data key is already verified and the device blob stays in place, so an auth key that
    // Android invalidated earlier (lock screen removed, then set again) can safely be replaced.
    const wrapped = await wrapPatientVaultKey(rawKey, 'auth', { replaceInvalidatedKey: true });
    await assertWrappedKeyOpens(wrapped, 'auth', rawKey);
    const next: NativeWrappedKey = { ...wrapped, protection: 'auth' };
    const recovery = await newRecovery(rawKey);
    const stored = await withPatientVaultMutation(async () => {
      const current = await readStoredVault();
      if (
        current?.mode !== 'native-keychain' ||
        (current.wrappedKey.protection ?? 'device') !== 'device' ||
        current.wrappedKey.ivBase64 !== legacy.ivBase64 ||
        current.wrappedKey.ciphertextBase64 !== legacy.ciphertextBase64
      ) {
        return false;
      }
      await writeStoredVault(
        { ...current, wrappedKey: next, recovery: recovery.blob },
        { strictDurability: true },
      );
      try {
        const readBack = await readStoredVault();
        if (
          readBack?.mode !== 'native-keychain' ||
          readBack.wrappedKey.protection !== 'auth' ||
          readBack.wrappedKey.ivBase64 !== next.ivBase64 ||
          readBack.wrappedKey.ciphertextBase64 !== next.ciphertextBase64
        ) {
          throw new PatientVaultError('Новая обёртка ключа не сохранилась.', 'storage');
        }
        if (!sameRecoveryBlob(readBack.recovery, recovery.blob)) {
          throw new PatientVaultError('Код восстановления не сохранился.', 'storage');
        }
        await assertWrappedKeyOpens(readBack.wrappedKey, 'auth', rawKey);
        await assertRecoveryOpens(readBack.recovery, recovery.code, rawKey);
      } catch (verification) {
        // The device key is still in the Keystore, so the record it opens can simply go back.
        await writeStoredVault(current, { strictDurability: true });
        throw verification;
      }
      return true;
    });
    if (!stored) return;
    // Both blobs are stored and proven: the doctor gets the code, then the old key may go.
    offerRecoveryCode(recovery.code, recovery.blob);
    await retireLegacyPatientVaultKey();
  } catch (error) {
    const code = nativeVaultErrorCode(error);
    if (code === 'AUTH_CANCELLED' || code === 'AUTH_FAILED') {
      throw nativeKeyError(error, 'Не удалось подтвердить.', 'unavailable');
    }
    console.warn('Хранилище осталось на прежнем ключе устройства.', error);
  }
}

/**
 * A vault that opened through the auth-bound key no longer needs the device key. This also
 * finishes an upgrade that was interrupted after its blob was stored; the plugin refuses unless
 * the auth key exists, and retiring twice is harmless.
 */
function retireLegacyKeyAfterAuthUnlock(): void {
  retireLegacyPatientVaultKey().catch((error: unknown) => {
    console.warn('Прежний ключ устройства не удалён.', error);
  });
}

/**
 * An auth-bound vault whose recovery code was never confirmed (or that has none, as the first
 * test builds made it) gets a fresh code on this unlock. The earlier blob was never confirmed, so
 * replacing it loses nothing; the new blob is stored, read back and proven before it is offered.
 * A failure is logged: the vault opens and tries again on the next unlock.
 */
async function ensureUnconfirmedRecovery(
  opened: NativeStoredVault,
  rawKey: Uint8Array,
): Promise<void> {
  if ((opened.wrappedKey.protection ?? 'device') !== 'auth' || opened.recovery?.confirmed) return;
  try {
    const fresh = await newRecovery(rawKey);
    const written = await withPatientVaultMutation(async () => {
      const current = await readStoredVault();
      if (
        current?.mode !== 'native-keychain' ||
        !sameWrappedKey(current.wrappedKey, opened.wrappedKey) ||
        current.recovery?.confirmed
      ) {
        return false;
      }
      await writeStoredVault({ ...current, recovery: fresh.blob }, { strictDurability: true });
      try {
        const readBack = await readStoredVault();
        if (
          readBack?.mode !== 'native-keychain' ||
          !sameRecoveryBlob(readBack.recovery, fresh.blob)
        ) {
          throw new PatientVaultError('Код восстановления не сохранился.', 'storage');
        }
        await assertRecoveryOpens(readBack.recovery, fresh.code, rawKey);
      } catch (verification) {
        await writeStoredVault(current, { strictDurability: true });
        throw verification;
      }
      return true;
    });
    if (written) offerRecoveryCode(fresh.code, fresh.blob);
  } catch (error) {
    console.warn('Код восстановления хранилища не сохранён.', error);
  }
}

/**
 * Opens a vault whose Keystore key is gone (or any vault, from Settings) with its recovery code,
 * and moves it onto a new key:
 *
 * 1. open the recovery blob with the typed code; a wrong code is `wrong-code` and nothing changes;
 * 2. prove the data key by decrypting the snapshot with it;
 * 3. wrap it under a new auth-bound key (system prompt) and seal it under a NEW recovery code;
 *    on a phone that no longer has a lock screen the plain device key wraps it and no code is kept;
 * 4. replace `wrappedKey` and `recovery` in one strict write, read the record back and prove both
 *    blobs again; a failed check puts the previous record back.
 *
 * The old code stays valid until step 4's write lands. A cancelled prompt leaves everything as it
 * was. The new code is offered through `pendingPatientVaultRecoveryCode`.
 */
export function recoverPatientVaultWithCode(code: string): Promise<PatientVaultSnapshot> {
  return withPatientVaultMutation(async () => {
    const stored = await readStoredVault();
    if (!stored) throw new PatientVaultError('Пациентское хранилище ещё не создано.', 'storage');
    if (stored.mode !== 'native-keychain' || !stored.recovery) {
      throw new PatientVaultError('Для этого хранилища нет кода восстановления.', 'unavailable');
    }
    const rawKey = await openDataKeyWithCode(stored.recovery, code);
    try {
      const key = await importDataKey(rawKey);
      let snapshot: PatientVaultSnapshot;
      try {
        const plain = await decryptBytes(stored.snapshot, key);
        snapshot = normalizePatientVaultSnapshot(
          JSON.parse(new TextDecoder().decode(plain)) as unknown,
        );
      } catch {
        throw new PatientVaultError('Повреждён снимок пациентского хранилища.', 'integrity');
      }
      const fresh = (await isNativePatientVaultAuthAvailable())
        ? await rewrapUnderAuthKey(stored, rawKey)
        : await rewrapUnderDeviceKey(stored, rawKey);
      lockPatientVault();
      session = { mode: 'native-keychain', key, rawKey };
      emit(PATIENT_VAULT_EVENT);
      if (fresh) offerRecoveryCode(fresh.code, fresh.blob);
      return snapshot;
    } catch (error) {
      rawKey.fill(0);
      throw error;
    }
  });
}

async function rewrapUnderAuthKey(
  stored: NativeStoredVault,
  rawKey: Uint8Array,
): Promise<{ readonly code: string; readonly blob: RecoveryBlob }> {
  let wrapped: NativeWrappedKeyShape;
  try {
    wrapped = await wrapPatientVaultKey(rawKey, 'auth', { replaceInvalidatedKey: true });
  } catch (error) {
    throw nativeKeyError(error, 'Keychain/Keystore не сохранил ключ хранилища.', 'storage');
  }
  const next: NativeWrappedKey = { ...wrapped, protection: 'auth' };
  const fresh = await newRecovery(rawKey);
  try {
    await assertWrappedKeyOpens(next, 'auth', rawKey);
  } catch (error) {
    throw nativeKeyError(error, 'Keychain/Keystore не открыл новый ключ хранилища.', 'storage');
  }
  await writeStoredVault(
    { ...stored, wrappedKey: next, recovery: fresh.blob },
    { strictDurability: true },
  );
  try {
    const readBack = await readStoredVault();
    if (
      readBack?.mode !== 'native-keychain' ||
      !sameWrappedKey(readBack.wrappedKey, next) ||
      !sameRecoveryBlob(readBack.recovery, fresh.blob)
    ) {
      throw new PatientVaultError('Новый ключ хранилища не сохранился.', 'storage');
    }
    await assertWrappedKeyOpens(readBack.wrappedKey, 'auth', rawKey);
    await assertRecoveryOpens(readBack.recovery, fresh.code, rawKey);
  } catch (verification) {
    await writeStoredVault(stored, { strictDurability: true });
    throw verification instanceof PatientVaultError
      ? verification
      : nativeKeyError(verification, 'Новый ключ хранилища не прошёл проверку.', 'storage');
  }
  return fresh;
}

/** The lock screen is gone for good: the device key holds the data key and needs no code. */
async function rewrapUnderDeviceKey(
  stored: NativeStoredVault,
  rawKey: Uint8Array,
): Promise<undefined> {
  let wrapped: NativeWrappedKeyShape;
  try {
    wrapped = await wrapPatientVaultKey(rawKey, 'device');
    await assertWrappedKeyOpens({ ...wrapped, protection: 'device' }, 'device', rawKey);
  } catch (error) {
    throw nativeKeyError(error, 'Keychain/Keystore не сохранил ключ хранилища.', 'storage');
  }
  const { recovery: _spent, ...withoutRecovery } = stored;
  await writeStoredVault(
    { ...withoutRecovery, wrappedKey: { ...wrapped, protection: 'device' } },
    { strictDurability: true },
  );
  try {
    const readBack = await readStoredVault();
    if (
      readBack?.mode !== 'native-keychain' ||
      readBack.wrappedKey.protection !== 'device' ||
      readBack.wrappedKey.ciphertextBase64 !== wrapped.ciphertextBase64
    ) {
      throw new PatientVaultError('Новый ключ хранилища не сохранился.', 'storage');
    }
    await assertWrappedKeyOpens(readBack.wrappedKey, 'device', rawKey);
  } catch (verification) {
    await writeStoredVault(stored, { strictDurability: true });
    throw verification instanceof PatientVaultError
      ? verification
      : nativeKeyError(verification, 'Новый ключ хранилища не прошёл проверку.', 'storage');
  }
  return undefined;
}

export async function unlockPatientVault(): Promise<PatientVaultSnapshot> {
  lockPatientVault();
  const stored = await readStoredVault();
  if (!stored) throw new PatientVaultError('Пациентское хранилище ещё не создано.', 'storage');
  if (stored.mode === 'unencrypted') {
    const snapshot = normalizePatientVaultSnapshot(stored.snapshot.data);
    session = { mode: 'unencrypted' };
    emit(PATIENT_VAULT_EVENT);
    return snapshot;
  }
  if (stored.mode === 'browser-device-key') {
    try {
      const plain = await decryptBytes(stored.snapshot, stored.key);
      const snapshot = normalizePatientVaultSnapshot(
        JSON.parse(new TextDecoder().decode(plain)) as unknown,
      );
      session = { mode: 'browser-device-key', key: stored.key };
      emit(PATIENT_VAULT_EVENT);
      return snapshot;
    } catch (error) {
      lockPatientVault();
      if (error instanceof PatientVaultError) throw error;
      throw new PatientVaultError('Повреждён снимок пациентского хранилища.', 'integrity');
    }
  }
  const protection = stored.wrappedKey.protection ?? 'device';
  let rawKey: Uint8Array;
  try {
    rawKey = await unwrapPatientVaultKey(stored.wrappedKey, protection);
  } catch (error) {
    throw nativeKeyError(error, 'Keychain/Keystore не открыл ключ хранилища.', 'unavailable');
  }
  try {
    const key = await importDataKey(rawKey);
    const plain = await decryptBytes(stored.snapshot, key);
    const snapshot = normalizePatientVaultSnapshot(
      JSON.parse(new TextDecoder().decode(plain)) as unknown,
    );
    // The key is proven good (it decrypted the snapshot) before anything is re-wrapped.
    if (protection === 'device') await upgradeToAuthProtection(stored.wrappedKey, rawKey);
    else {
      retireLegacyKeyAfterAuthUnlock();
      await ensureUnconfirmedRecovery(stored, rawKey);
    }
    session = { mode: 'native-keychain', key, rawKey };
    emit(PATIENT_VAULT_EVENT);
    return snapshot;
  } catch (error) {
    rawKey.fill(0);
    lockPatientVault();
    if (error instanceof PatientVaultError) throw error;
    throw new PatientVaultError('Повреждён снимок пациентского хранилища.', 'integrity');
  }
}

/**
 * Opens the vault without asking when no choice is needed (ADR-0016): an open session is read, an
 * encrypted vault is unlocked, a missing one is created encrypted. Returns `undefined` when the
 * person would have to decide (a plaintext vault); a failure is thrown for the caller to report.
 */
export async function openPatientVaultSilently(): Promise<PatientVaultSnapshot | undefined> {
  if (isPatientVaultUnlocked()) return readPatientVault();
  const mode = await patientVaultStorageMode();
  if (isEncryptedPatientVaultMode(mode)) return unlockPatientVault();
  if (!mode) {
    await createPatientVault();
    return readPatientVault();
  }
  return undefined;
}

export async function readPatientVault(): Promise<PatientVaultSnapshot> {
  if (!session) throw new PatientVaultLockedError();
  try {
    const stored = await readStoredVault();
    if (!stored || stored.mode !== session.mode) throw new PatientVaultLockedError();
    if (stored.mode === 'unencrypted') {
      return normalizePatientVaultSnapshot(stored.snapshot.data);
    }
    if (session.mode === 'unencrypted') throw new PatientVaultLockedError();
    const plain = await decryptBytes(stored.snapshot, session.key);
    return normalizePatientVaultSnapshot(JSON.parse(new TextDecoder().decode(plain)) as unknown);
  } catch (error) {
    lockPatientVault();
    if (error instanceof PatientVaultError) throw error;
    throw new PatientVaultError('Повреждён снимок пациентского хранилища.', 'integrity');
  }
}

/** A short text sealed with the vault's data key (or kept as is in a deliberately plain vault). */
export type SealedPatientText =
  | { readonly plain: string }
  | { readonly iv: string; readonly aad: string; readonly ciphertext: string };

const SEALED_TEXT_VERSION = PATIENT_VAULT_SCHEMA_VERSION;

/**
 * Seals text for storage outside the vault database (a write-ahead copy kept in localStorage until
 * the vault write lands). Needs an open session; the same key and AAD scheme as vault records.
 */
export async function sealPatientVaultText(
  type: string,
  id: string,
  text: string,
): Promise<SealedPatientText> {
  const current = session;
  if (!current) throw new PatientVaultLockedError();
  if (current.mode === 'unencrypted') return { plain: text };
  return encryptBytes(current.key, utf8(text), type, id);
}

export async function openPatientVaultText(
  type: string,
  id: string,
  sealed: SealedPatientText,
): Promise<string> {
  const current = session;
  if (!current) throw new PatientVaultLockedError();
  if ('plain' in sealed) {
    if (current.mode !== 'unencrypted') {
      throw new PatientVaultError('Неверная целостность записи.', 'integrity');
    }
    return sealed.plain;
  }
  if (current.mode === 'unencrypted') throw new PatientVaultLockedError();
  const plain = await decryptBytes(
    { ...sealed, type, id, version: SEALED_TEXT_VERSION },
    current.key,
  );
  return new TextDecoder().decode(plain);
}

export async function writePatientVault(snapshot: PatientVaultSnapshot): Promise<void> {
  if (!session) throw new PatientVaultLockedError();
  try {
    const stored = await readStoredVault();
    if (!stored) throw new PatientVaultError('Пациентское хранилище не найдено.', 'storage');
    await writeStoredVault(await storedVaultWithSnapshot(stored, snapshot));
    emit(PATIENT_VAULT_EVENT);
  } catch (error) {
    lockPatientVault();
    throw error;
  }
}

export function updatePatientVault(
  update: (snapshot: PatientVaultSnapshot) => PatientVaultSnapshot | Promise<PatientVaultSnapshot>,
): Promise<PatientVaultSnapshot> {
  return withPatientVaultMutation(async () => {
    const snapshot = await readPatientVault();
    const next = await update(snapshot);
    if (next !== snapshot) await writePatientVault(next);
    return next;
  });
}

export async function createPatientInVault(input: CreatePatientProfileInput): Promise<{
  readonly snapshot: PatientVaultSnapshot;
  readonly patientId: string;
}> {
  const created = createPatientProfile(input);
  const snapshot = await updatePatientVault((current) => {
    let next: PatientVaultSnapshot = {
      ...current,
      profiles: [...current.profiles, created.profile],
    };
    for (const event of created.initialEvents) next = appendEvent(next, event);
    return next;
  });
  return { snapshot, patientId: created.profile.id };
}

async function storedBlob(input: {
  readonly id: string;
  readonly patientId?: string;
  readonly mimeType: string;
  readonly bytes: Uint8Array;
}): Promise<StoredBlob> {
  if (!session) throw new PatientVaultLockedError();
  const base: StoredBlobBase = {
    type: 'patient-file',
    id: input.id,
    version: PATIENT_VAULT_SCHEMA_VERSION,
    mimeType: input.mimeType,
    ...(input.patientId ? { patientId: input.patientId } : {}),
  };
  if (session.mode === 'unencrypted') {
    return { ...base, storage: 'plaintext', bytes: input.bytes.slice() };
  }
  return {
    ...base,
    storage: 'encrypted',
    ...(await encryptBytes(session.key, input.bytes, 'patient-file', input.id)),
  };
}

/** File writers share the mutation queue, so an in-place encryption never misses a file. */
export function addPatientBlob(input: {
  readonly id: string;
  readonly patientId?: string;
  readonly mimeType: string;
  readonly bytes: Uint8Array;
}): Promise<void> {
  return withPatientVaultMutation(async () => {
    if (!session) throw new PatientVaultLockedError();
    if (!input.id.trim() || !input.mimeType.trim()) {
      throw new PatientVaultError('Файл пациента имеет неверные метаданные.', 'storage');
    }
    try {
      if (input.patientId !== undefined) {
        const snapshot = await readPatientVault();
        if (!snapshot.profiles.some((profile) => profile.id === input.patientId)) {
          throw new PatientVaultError('Файл относится к неизвестному пациенту.', 'storage');
        }
      }
      // Encrypt first: an IndexedDB transaction does not stay open across Web Crypto's async work.
      const blob = await storedBlob(input);
      const database = await openDatabase();
      try {
        const transaction = database.transaction(BLOB_STORE, 'readwrite');
        transaction.objectStore(BLOB_STORE).put(blob);
        await transactionDone(transaction);
      } finally {
        database.close();
      }
    } catch (error) {
      lockPatientVault();
      throw error;
    }
  });
}

async function blobBytes(blob: StoredBlob): Promise<Uint8Array> {
  assertStoredBlob(blob);
  if (!session) throw new PatientVaultLockedError();
  if (blob.storage === 'plaintext') {
    if (session.mode !== 'unencrypted') throw new PatientVaultLockedError();
    return blob.bytes.slice();
  }
  if (session.mode === 'unencrypted') throw new PatientVaultLockedError();
  return decryptBytes(blob, session.key);
}

export async function readPatientBlob(
  id: string,
): Promise<{ readonly mimeType: string; readonly bytes: Uint8Array } | undefined> {
  if (!session) throw new PatientVaultLockedError();
  try {
    const database = await openDatabase();
    try {
      const transaction = database.transaction(BLOB_STORE, 'readonly');
      const done = transactionDone(transaction);
      const stored = await requestResult(
        transaction.objectStore(BLOB_STORE).get(id) as IDBRequest<StoredBlob | undefined>,
      );
      await done;
      return stored ? { mimeType: stored.mimeType, bytes: await blobBytes(stored) } : undefined;
    } finally {
      database.close();
    }
  } catch (error) {
    lockPatientVault();
    throw error;
  }
}

/** Removes one stored file (for example a draft transcript of a deleted recording). */
export function deletePatientBlob(id: string): Promise<void> {
  return withPatientVaultMutation(async () => {
    if (!session) throw new PatientVaultLockedError();
    try {
      const database = await openDatabase();
      try {
        const transaction = database.transaction(BLOB_STORE, 'readwrite');
        transaction.objectStore(BLOB_STORE).delete(id);
        await transactionDone(transaction);
      } finally {
        database.close();
      }
    } catch (error) {
      lockPatientVault();
      throw error;
    }
  });
}

async function writeSnapshotAndDeletePatientBlobs(
  snapshot: PatientVaultSnapshot,
  patientId: string,
): Promise<void> {
  if (!session) throw new PatientVaultLockedError();
  const stored = await readStoredVault();
  if (!stored) throw new PatientVaultError('Пациентское хранилище не найдено.', 'storage');
  const nextStored = await storedVaultWithSnapshot(stored, snapshot);
  const database = await openDatabase();
  try {
    const transaction = database.transaction([VAULT_STORE, BLOB_STORE], 'readwrite');
    transaction.objectStore(VAULT_STORE).put(nextStored, VAULT_KEY);
    const blobStore = transaction.objectStore(BLOB_STORE);
    const done = transactionDone(transaction);
    const getAll = blobStore.getAll() as IDBRequest<StoredBlob[]>;
    await new Promise<void>((resolve, reject) => {
      getAll.onsuccess = () => {
        for (const blob of getAll.result) {
          if (blob.patientId === patientId) blobStore.delete(blob.id);
        }
        resolve();
      };
      getAll.onerror = () =>
        reject(getAll.error ?? new PatientVaultError('Ошибка IndexedDB.', 'storage'));
    });
    await done;
  } finally {
    database.close();
  }
}

export async function deletePatientFromVault(patientId: string): Promise<void> {
  try {
    await withPatientVaultMutation(async () => {
      const snapshot = await readPatientVault();
      await writeSnapshotAndDeletePatientBlobs(
        removePatientFromSnapshot(snapshot, patientId),
        patientId,
      );
      emit(PATIENT_VAULT_EVENT);
    });
  } catch (error) {
    lockPatientVault();
    throw error;
  }
}

export async function exportPatientVaultBackup(patientId?: string): Promise<PatientVaultBackup> {
  if (!session) throw new PatientVaultLockedError();
  try {
    const sourceSnapshot = await readPatientVault();
    const snapshot = patientId
      ? selectPatientFromSnapshot(sourceSnapshot, patientId)
      : sourceSnapshot;
    const database = await openDatabase();
    try {
      const transaction = database.transaction(BLOB_STORE, 'readonly');
      const done = transactionDone(transaction);
      const storedBlobs = await requestResult(
        transaction.objectStore(BLOB_STORE).getAll() as IDBRequest<StoredBlob[]>,
      );
      await done;
      const selected = patientId
        ? storedBlobs.filter((blob) => blob.patientId === patientId)
        : storedBlobs;
      const blobs: PatientVaultBackupBlob[] = [];
      for (const blob of selected) {
        blobs.push({
          id: blob.id,
          mimeType: blob.mimeType,
          ...(blob.patientId ? { patientId: blob.patientId } : {}),
          bytesBase64: bytesToBase64(await blobBytes(blob)),
        });
      }
      return parseBackup({
        kind: 'minimed-patient-vault-backup',
        schemaVersion: PATIENT_VAULT_SCHEMA_VERSION,
        snapshot,
        blobs,
      });
    } finally {
      database.close();
    }
  } catch (error) {
    if (isPatientVaultUnlocked()) lockPatientVault();
    throw error;
  }
}

export function importPatientVaultBackup(value: unknown): Promise<void> {
  return withPatientVaultMutation(() => replaceVaultFromBackup(value));
}

async function replaceVaultFromBackup(value: unknown): Promise<void> {
  if (!session) throw new PatientVaultLockedError();
  try {
    const backup = parseBackup(value);
    const stored = await readStoredVault();
    if (!stored) throw new PatientVaultError('Пациентское хранилище не найдено.', 'storage');
    const nextStored = await storedVaultWithSnapshot(stored, backup.snapshot);
    const nextBlobs: StoredBlob[] = [];
    for (const blob of backup.blobs) {
      nextBlobs.push(
        await storedBlob({
          id: blob.id,
          mimeType: blob.mimeType,
          ...(blob.patientId ? { patientId: blob.patientId } : {}),
          bytes: base64ToBytes(blob.bytesBase64),
        }),
      );
    }
    const database = await openDatabase();
    try {
      const transaction = database.transaction([VAULT_STORE, BLOB_STORE], 'readwrite');
      transaction.objectStore(VAULT_STORE).put(nextStored, VAULT_KEY);
      const blobStore = transaction.objectStore(BLOB_STORE);
      blobStore.clear();
      for (const blob of nextBlobs) blobStore.put(blob);
      await transactionDone(transaction);
    } finally {
      database.close();
    }
    emit(PATIENT_VAULT_EVENT);
  } catch (error) {
    lockPatientVault();
    if (error instanceof PatientVaultError) throw error;
    throw new PatientVaultError('Повреждён снимок резервной копии.', 'integrity');
  }
}

export async function deletePatientVault(): Promise<void> {
  lockPatientVault();
  await deletePatientVaultNativeKey();
  await Promise.all([deleteDatabase(DATABASE_NAME), ...LEGACY_DATABASE_NAMES.map(deleteDatabase)]);
  emit(PATIENT_VAULT_EVENT);
}

export function installPatientVaultLifecycle(
  onLock = lockPatientVault,
  vaultIsUnlocked = isPatientVaultUnlocked,
): () => void {
  lifecycleCleanup?.();
  if (typeof window === 'undefined') return () => undefined;
  let timer: ReturnType<typeof setTimeout> | undefined;
  let patientUiCleared = false;
  const cancelScheduledLock = (): void => {
    if (!timer) return;
    clearTimeout(timer);
    timer = undefined;
  };
  const setCurtain = (): void => {
    document.documentElement.classList.add('patient-vault--privacy-curtain');
  };
  const clearCurtain = (): void => {
    if (document.visibilityState === 'hidden') return;
    if (vaultIsUnlocked() || patientUiCleared) {
      document.documentElement.classList.remove('patient-vault--privacy-curtain');
    }
  };
  const scheduleLock = (): void => {
    if (!vaultIsUnlocked()) return;
    cancelScheduledLock();
    timer = setTimeout(() => {
      timer = undefined;
      setCurtain();
      onLock();
    }, 5 * 60_000);
  };
  const immediatePrivacy = (): void => {
    if (!vaultIsUnlocked()) return;
    setCurtain();
    scheduleLock();
  };
  const restorePrivacy = (): void => {
    if (vaultIsUnlocked()) {
      patientUiCleared = false;
      clearCurtain();
      scheduleLock();
    } else {
      clearCurtain();
    }
  };
  const onActivity = (): void => {
    if (document.visibilityState === 'visible') scheduleLock();
  };
  const onVisibility = (): void =>
    document.visibilityState === 'hidden' ? immediatePrivacy() : restorePrivacy();
  const onPageHide = (): void => {
    if (!vaultIsUnlocked()) return;
    immediatePrivacy();
    onLock();
  };
  const onVaultChange = (): void => {
    if (vaultIsUnlocked()) {
      patientUiCleared = false;
      clearCurtain();
      scheduleLock();
      return;
    }
    cancelScheduledLock();
    patientUiCleared = false;
    setCurtain();
  };
  const onPatientUiCleared = (): void => {
    patientUiCleared = true;
    clearCurtain();
  };
  document.addEventListener('visibilitychange', onVisibility);
  window.addEventListener('blur', immediatePrivacy);
  window.addEventListener('focus', restorePrivacy);
  window.addEventListener('pagehide', onPageHide);
  window.addEventListener('pointerdown', onActivity, { passive: true });
  window.addEventListener('keydown', onActivity, { passive: true });
  window.addEventListener('touchstart', onActivity, { passive: true });
  window.addEventListener('mousemove', onActivity, { passive: true });
  window.addEventListener(PATIENT_VAULT_EVENT, onVaultChange);
  window.addEventListener(PATIENT_VAULT_LOCK_EVENT, onVaultChange);
  window.addEventListener(PATIENT_VAULT_UI_CLEARED_EVENT, onPatientUiCleared);
  scheduleLock();
  lifecycleCleanup = () => {
    cancelScheduledLock();
    document.removeEventListener('visibilitychange', onVisibility);
    window.removeEventListener('blur', immediatePrivacy);
    window.removeEventListener('focus', restorePrivacy);
    window.removeEventListener('pagehide', onPageHide);
    window.removeEventListener('pointerdown', onActivity);
    window.removeEventListener('keydown', onActivity);
    window.removeEventListener('touchstart', onActivity);
    window.removeEventListener('mousemove', onActivity);
    window.removeEventListener(PATIENT_VAULT_EVENT, onVaultChange);
    window.removeEventListener(PATIENT_VAULT_LOCK_EVENT, onVaultChange);
    window.removeEventListener(PATIENT_VAULT_UI_CLEARED_EVENT, onPatientUiCleared);
    if (document.visibilityState !== 'hidden' && vaultIsUnlocked()) {
      document.documentElement.classList.remove('patient-vault--privacy-curtain');
    }
    lifecycleCleanup = undefined;
  };
  return lifecycleCleanup;
}

