export type PatientVaultStorageMode = 'native-keychain' | 'browser-device-key' | 'unencrypted';

/** True for the modes whose snapshot and files are encrypted by a device-held key. */
export function isEncryptedPatientVaultMode(
  mode: PatientVaultStorageMode | undefined,
): mode is Exclude<PatientVaultStorageMode, 'unencrypted'> {
  return mode === 'native-keychain' || mode === 'browser-device-key';
}

interface NativeWrappedKey {
  readonly ivBase64: string;
  readonly ciphertextBase64: string;
  /** Which Keystore key wrapped it; a record from before the fingerprint unlock has none (`device`). */
  readonly protection?: NativeKeyProtection;
}

/**
 * The data key sealed with a key derived from the recovery code. Stored beside the Keystore-wrapped
 * key of an auth-bound vault; the code is not stored anywhere.
 */
interface RecoveryBlob {
  readonly ivBase64: string;
  readonly ciphertextBase64: string;
  /** The doctor confirmed writing the code down. Until then every unlock offers a fresh code. */
  readonly confirmed: boolean;
}

