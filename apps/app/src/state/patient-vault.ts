export class PatientVaultError extends Error {
  public constructor(
    message: string,
    public readonly code:
      | 'unavailable'
      | 'integrity'
      | 'locked'
      | 'storage'
      /** The fingerprint / PIN check did not happen (cancelled, failed): nothing is lost, retry. */
      | 'auth-required'
      /** The Keystore key was removed (lock screen removed or changed): recovery code or backup. */
      | 'key-invalidated'
      /** The recovery code does not open this vault; nothing was changed. */
      | 'wrong-code',
  ) {
    super(message);
    this.name = 'PatientVaultError';
  }
}

export class PatientVaultLockedError extends PatientVaultError {
  public constructor() {
    super('Пациентское хранилище заблокировано.', 'locked');
  }
}

