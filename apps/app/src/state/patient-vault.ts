/**
 * Patient vault: one IndexedDB database holding an encrypted (or, as a last resort, plain)
 * snapshot and the patient's files. Three storage modes:
 *
 * - `native-keychain`: Android Keystore wraps a random AES-256 data key. On a phone with a secure
 *   lock screen the wrapping key is auth-bound (`protection: 'auth'`): opening the vault asks for a
 *   fingerprint, face or device PIN, and one check stays valid for a few minutes. Without a lock
 *   screen, and for vaults made before this, the wrapping key is the plain device key
 *   (`protection: 'device'`), unlocked silently. A `device` vault moves to an auth-bound key on its
 *   next unlock, see `upgradeToAuthProtection`. Android deletes an auth-bound key when the lock
 *   screen is removed or changed, so every auth-bound vault also keeps the data key sealed under a
 *   recovery code (`recovery`, the diary's code format and key derivation). The code itself is
 *   shown once and never stored; see `recoverPatientVaultWithCode`;
 * - `browser-device-key`: a non-extractable WebCrypto AES-GCM key generated by this browser and
 *   stored beside the data in the same IndexedDB record. It is used exactly like the native data
 *   key (same `encryptBytes`/AAD scheme for the snapshot and every file);
 * - `unencrypted`: explicit fallback when the browser cannot keep a key. A vault in this mode can
 *   be upgraded in place with `encryptPatientVault()`.
 *
 * Threat model of `browser-device-key`: the key cannot be read back by script (`extractable:false`),
 * so a copy of the stored data taken off the device or out of an exported browser profile is
 * ciphertext without a usable key. It does NOT protect against code running in this origin (it can
 * call `decrypt` through the stored key), against someone using this unlocked browser profile, or
 * against clearing site data (which deletes key and data together). Real patients belong in the
 * Android app, where the key sits in the hardware-backed Keystore.
 */
