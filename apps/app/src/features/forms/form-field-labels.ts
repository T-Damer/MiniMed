/** Sentence case: the first letter is a capital, the rest is left as written. */
function sentenceCase(text: string): string {
  return text.charAt(0).toLocaleUpperCase('ru-RU') + text.slice(1);
}

export function plainFieldLabel(official: string): string {
  const exact = PLAIN_LABELS.get(official);
  if (exact) return exact;
  const cleaned = official
    // The codes of the ICD: «код по … (далее – МКБ) (причина инвалидности)» → «Код МКБ (причина инвалидности)».
    .replace(
      /код по Международной статистической классификации болезней и проблем, связанных со здоровьем\s*\(далее\s*[–-]\s*МКБ\)/iu,
      'Код МКБ',
    )
    .replace(/^код по МКБ/u, 'Код МКБ')
    .replace(/\s*\(при наличии\)/gu, '')
    .replace(/Фамилия, имя, отчество/gu, 'ФИО')
    .replace(/обязательного медицинского страхования/gu, 'ОМС')
    .replace(/\s{2,}/gu, ' ')
    .trim();
  return sentenceCase(cleaned);
}
