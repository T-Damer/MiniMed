/**
 * Looks up canonical reference information for a receptor target label from a drug profile
 * (e.g. «D2L», «5-HT2A», «H1», «α1», «SERT», «GABA-A (BZD-сайт)»).
 */
export function lookupReceptorInfo(receptorLabel: string): ReceptorReferenceInfo | null {
  const cleaned = receptorLabel.trim();
  if (!cleaned) return null;
  for (const entry of RECEPTOR_ENCYCLOPEDIA) {
    if (entry.match.test(cleaned)) return entry;
  }
  const upper = cleaned.toUpperCase();
  if (upper.includes('ГАМК') || upper.includes('GABA')) {
    return RECEPTOR_ENCYCLOPEDIA.find((item) => item.canonical === 'GABA-A') ?? null;
  }
  if (upper.includes('НАТРИ') || upper.includes('VGSC') || upper.includes('NA+')) {
    return RECEPTOR_ENCYCLOPEDIA.find((item) => item.canonical === 'VGSC') ?? null;
  }
  if (upper.includes('GSK') || upper.includes('ИНОЗИТОЛ')) {
    return RECEPTOR_ENCYCLOPEDIA.find((item) => item.canonical === 'GSK-3β / IMPA') ?? null;
  }
  if (upper.includes('ФДЭ') || upper.includes('PDE') || upper.includes('2,3-')) {
    return RECEPTOR_ENCYCLOPEDIA.find((item) => item.canonical === 'PDE / 2,3-BDZ') ?? null;
  }
  return null;
}
