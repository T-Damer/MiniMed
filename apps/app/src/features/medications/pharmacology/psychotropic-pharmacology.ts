function lookupBbbProfile(inns: readonly string[]): DrugBbbPenetration | undefined {
  for (const inn of inns) {
    const found = PSYCHOTROPIC_BBB_BY_INN[normalizeInnLookupKey(inn)];
    if (found) return found;
  }
  return undefined;
}

