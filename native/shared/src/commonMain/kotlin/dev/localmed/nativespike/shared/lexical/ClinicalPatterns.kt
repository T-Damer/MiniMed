/** ECMAScript word boundaries are ASCII, even around Cyrillic clinical words. */
internal fun clinicalRegex(pattern: String,ignoreCase: Boolean=true): Regex {
    val space="\\t\\n\\u000b\\u000c\\r \\u00a0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000\\ufeff"
    val word="A-Za-z0-9_"
    val adapted=buildString {
        var inClass=false;var index=0
        while(index<pattern.length) {
            val c=pattern[index++]
            if(c=='\\' && index<pattern.length) {
                val escaped=pattern[index++]
                when(escaped) {
                    's','w','d' -> { val chars=when(escaped) { 's' -> space;'w' -> word;else -> "0-9" };append(if(inClass) chars else "[$chars]") }
                    'b' -> append(if(inClass) "\\u0008" else "(?:(?<=[$word])(?![$word])|(?<![$word])(?=[$word]))")
                    else -> append('\\').append(escaped)
                }
            } else { if(c=='[') inClass=true else if(c==']') inClass=false;append(c) }
        }
    }
    return Regex(adapted,if(ignoreCase) setOf(RegexOption.IGNORE_CASE) else emptySet())
}

