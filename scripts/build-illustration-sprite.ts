/**
 * Builds `apps/app/src/assets/illustrations/illustrations.sprite.svg` from the single illustrations
 * in `svg/`: one `<symbol id="ill-<name>">` per file, every inner id prefixed with the file name so
 * the gradients of different illustrations never collide. Use: `<svg><use href="…sprite.svg#ill-lock"/></svg>`.
 *
 *   bun scripts/build-illustration-sprite.ts [--check]
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../apps/app/src/assets/illustrations');
const out = join(root, 'illustrations.sprite.svg');
const names = readdirSync(join(root, 'svg'))
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .toSorted();

const symbols = names.map((name) => {
  const source = readFileSync(join(root, 'svg', `${name}.svg`), 'utf8');
  const viewBox = /viewBox="([^"]+)"/u.exec(source)?.[1] ?? '0 0 512 512';
  const body = source
    .replace(/<\?xml[^>]*>/u, '')
    .replace(/<svg\b[^>]*>/u, '')
    .replace(/<\/svg>\s*$/u, '')
    .replace(/\bid="([^"]+)"/gu, `id="${name}-$1"`)
    .replace(/url\(#([^)]+)\)/gu, `url(#${name}-$1)`)
    .replace(/href="#([^"]+)"/gu, `href="#${name}-$1"`)
    .trim();
  return `  <symbol id="ill-${name}" viewBox="${viewBox}">\n${body}\n  </symbol>`;
});

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"><title>Иллюстрации MiniMed</title>\n<!-- Generated by scripts/build-illustration-sprite.ts from svg/*.svg; do not edit. -->\n${symbols.join('\n')}\n</svg>\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== sprite) {
    console.error(
      'illustrations.sprite.svg is out of date: run bun scripts/build-illustration-sprite.ts',
    );
    process.exit(1);
  }
} else {
  writeFileSync(out, sprite);
  console.log(`${names.length} illustrations → ${out}`);
}
